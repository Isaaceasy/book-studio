#!/usr/bin/env python
"""Batch figure helper for /interior-images (V4).

HiggsField is an assistant tool, so the generation calls are made by Claude
(generate_image_batch). This script does the parts a script can do:

  plan   books/<slug>/images/figure-plan.csv -> images/batch-jobs.json
         (tiered, chunked prompt list that Claude sends to generate_image_batch,
          with the fixed negative rules appended to every prompt)
  check  inspects every figure file in images/ (size, pixels per inch at the
         printed width, SVG safety) and prints PASS / WARN / FAIL per file
  log    writes verification/figure-log.md from the plan, images/jobs.csv
         (figure,job_id,attempt,decision,date) and the check results
  sheet  contact sheet PNG of all figures for the owner's quick review

Usage:
  python scripts/figure_pipeline.py plan  books/<slug> [--chunk 4]
  python scripts/figure_pipeline.py check books/<slug> [--width-in 3.3]
  python scripts/figure_pipeline.py log   books/<slug>
  python scripts/figure_pipeline.py sheet books/<slug> [--out sheet.png]

figure-plan.csv columns: id,chapter,tier,route,aspect,subject,prompt,caption,alt
  route = SVG or AI. Only AI rows go into batch-jobs.json.
"""
import argparse, base64, csv, io, json, re, sys, datetime
from pathlib import Path

NEG = ("No text, letters, numbers, labels or watermarks inside the image. "
       "No logos, brands or real people. Single clear subject, plain background.")
MIN_PPI_FAIL, MIN_PPI_WARN = 200, 300


def read_plan(book):
    p = book / "images" / "figure-plan.csv"
    if not p.exists():
        sys.exit(f"missing {p}")
    with open(p, newline="", encoding="utf-8-sig") as f:
        return list(csv.DictReader(f))


def fig_file(book, fid):
    for ext in (".png", ".jpg", ".jpeg", ".svg"):
        q = book / "images" / f"{fid}{ext}"
        if q.exists():
            return q
    return None


def svg_embedded(p):
    """Return the first embedded raster of an SVG as a PIL image, or None (AI figures are placed this way)."""
    from PIL import Image
    t = p.read_text(encoding="utf-8", errors="ignore")
    m = re.search(r"data:image/(?:png|jpe?g);base64,([A-Za-z0-9+/=\s]+)", t)
    return Image.open(io.BytesIO(base64.b64decode(re.sub(r"\s", "", m.group(1))))) if m else None


def cmd_plan(a):
    book = Path(a.book)
    rows = [r for r in read_plan(book) if r.get("route", "").upper() == "AI"]
    jobs = [{"id": r["id"], "aspect_ratio": r.get("aspect") or "3:4",
             "prompt": f'{r["prompt"].strip()} {NEG}'} for r in rows]
    chunks = [jobs[i:i + a.chunk] for i in range(0, len(jobs), a.chunk)]
    out = book / "images" / "batch-jobs.json"
    out.write_text(json.dumps({"chunks": chunks,
        "note": "Send one chunk at a time to generate_image_batch; on a 429 wait and retry the failed ids only; "
                "record every job id in images/jobs.csv (figure,job_id,attempt,decision,date)."}, indent=2), encoding="utf-8")
    print(f"{len(jobs)} AI figures in {len(chunks)} chunk(s) -> {out}")


def cmd_check(a):
    try:
        from PIL import Image
    except ImportError:
        sys.exit("Pillow missing: pip install pillow")
    book = Path(a.book)
    bad = 0
    for p in sorted((book / "images").glob("*")):
        if p.suffix.lower() in (".png", ".jpg", ".jpeg"):
            w, h = Image.open(p).size
            ppi = w / a.width_in
            st = "FAIL" if ppi < MIN_PPI_FAIL else "WARN" if ppi < MIN_PPI_WARN else "PASS"
            bad += st == "FAIL"
            print(f"{st:5} {p.name}  {w}x{h}px  {ppi:.0f} ppi at {a.width_in} in")
        elif p.suffix.lower() == ".svg":
            t = p.read_text(encoding="utf-8", errors="ignore")
            issues = [k for k, rx in (("script", r"<script"), ("external href", r'href="https?:'),
                                      ("web font", r"@import|font-face")) if re.search(rx, t)]
            im = svg_embedded(p)
            note = ""
            st = "FAIL" if issues else "PASS"
            if im:
                ppi = im.size[0] / a.width_in
                note = f"embedded {im.size[0]}x{im.size[1]}px, {ppi:.0f} ppi at {a.width_in} in"
                if not issues:
                    st = "FAIL" if ppi < MIN_PPI_FAIL else "WARN" if ppi < MIN_PPI_WARN else "PASS"
            bad += st == "FAIL"
            print(f"{st:5} {p.name}  svg {', '.join(issues)} {note}".rstrip())
    sys.exit(1 if bad else 0)


def cmd_log(a):
    book = Path(a.book)
    plan = read_plan(book)
    jobs = {}
    jp = book / "images" / "jobs.csv"
    if jp.exists():
        with open(jp, newline="", encoding="utf-8-sig") as f:
            for r in csv.DictReader(f):
                jobs.setdefault(r["figure"], []).append(r)
    lines = ["# Figure Log (generated by figure_pipeline.py "
             f"{datetime.date.today()})", "",
             "| Figure | Tier | Route | Brief | Job ids (attempts) | File | Reviewer decision | Caption | Alt text |",
             "|---|---|---|---|---|---|---|---|---|"]
    for r in plan:
        js = jobs.get(r["id"], [])
        ids = "; ".join(f'{j["job_id"]} (#{j.get("attempt","")}, {j.get("decision","")})' for j in js) or "n/a"
        f = fig_file(book, r["id"])
        lines.append("| " + " | ".join([r["id"], r.get("tier", ""), r.get("route", ""), r.get("subject", ""),
                                         ids, f.name if f else "MISSING", "pending", r.get("caption", ""), r.get("alt", "")]) + " |")
    out = book / "verification" / "figure-log.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    miss = [r["id"] for r in plan if not fig_file(book, r["id"])]
    print(f"wrote {out}; missing files: {miss or 'none'}")


def cmd_sheet(a):
    from PIL import Image, ImageDraw
    book = Path(a.book)
    files = [p for p in sorted((book / "images").glob("*")) if p.suffix.lower() in (".png", ".jpg", ".jpeg", ".svg")]
    if not files:
        sys.exit("no figures found")
    cell, cols = 260, 4
    rows = (len(files) + cols - 1) // cols
    sheet = Image.new("RGB", (cols * cell, rows * (cell + 20)), "white")
    d = ImageDraw.Draw(sheet)
    for i, p in enumerate(files):
        im = svg_embedded(p) if p.suffix.lower() == ".svg" else Image.open(p)
        if im is None:  # pure vector figure: placeholder tile, it is checked in the build preview
            im = Image.new("RGB", (cell, cell), "#eeeeee")
        im = im.convert("RGB")
        im.thumbnail((cell - 10, cell - 10))
        x, y = (i % cols) * cell, (i // cols) * (cell + 20)
        sheet.paste(im, (x + 5, y + 5))
        d.text((x + 5, y + cell + 3), p.name, fill="black")
    out = Path(a.out) if a.out else book / "images" / "contact-sheet.png"
    sheet.save(out)
    print(f"{len(files)} figures -> {out}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=["plan", "check", "log", "sheet"])
    ap.add_argument("book")
    ap.add_argument("--chunk", type=int, default=4)
    ap.add_argument("--width-in", type=float, default=3.3)
    ap.add_argument("--out")
    a = ap.parse_args()
    {"plan": cmd_plan, "check": cmd_check, "log": cmd_log, "sheet": cmd_sheet}[a.cmd](a)
